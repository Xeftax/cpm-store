#!/usr/bin/env python3
"""Génère docs/TREE.md — AUTO-GÉNÉRÉ, ne jamais éditer à la main.

Pour changer une description : corriger le `//!` du fichier source, puis relancer :
    python3 tools/generate-filemap.py

Porté du FILEMAP de tetrixx-tools (doc-station) adapté à Rust : la "docstring de module"
d'un fichier .rs est son header `//!`. Format : arbre indenté par dossier, une section par
langage, descriptions alignées en colonne.
"""

import datetime
import pathlib
import subprocess

ROOT = pathlib.Path(
    subprocess.check_output(["git", "rev-parse", "--show-toplevel"], text=True).strip()
)
OUT = ROOT / "docs" / "TREE.md"

# (titre de section, glob, marqueur de docstring de module)
SECTIONS = [
    ("Rust", "*.rs", "//!"),
    ("Markdown", "*.md", "# "),
    ("TOML", "*.toml", "# "),
]


def first_doc_line(path: pathlib.Path, marker: str) -> str:
    try:
        with open(path, encoding="utf-8", errors="replace") as f:
            for line in f:
                line = line.rstrip("\n")
                if line.startswith(marker):
                    return line[len(marker):].strip()
                if line.strip() and not line.startswith(marker):
                    return ""  # le header ne commence pas par le marqueur
    except OSError:
        return ""
    return ""


def build_tree(paths: list[str]) -> dict:
    tree: dict = {}
    for p in paths:
        parts = p.split("/")
        node = tree
        for part in parts[:-1]:
            node = node.setdefault(part, {})
        node[parts[-1]] = None  # feuille = fichier
    return tree


def render(node: dict, prefix: str, lines: list[str], width: int) -> None:
    dirs = sorted(k for k, v in node.items() if isinstance(v, dict))
    files = sorted(k for k, v in node.items() if not isinstance(v, dict))
    for d in dirs:
        lines.append(f"{prefix}{d}/")
        render(node[d], prefix + "  ", lines, width)
    for fname in files:
        desc = node[fname]
        lines.append(f"{prefix}{fname:<{width}} — {desc if desc else '(no docstring)'}")


def main() -> None:
    all_files = subprocess.check_output(
        ["git", "ls-files"], text=True, cwd=ROOT
    ).splitlines()
    # .vibe/ exclu : les skills/hooks sont déjà découverts par le harness (skill_paths),
    # TREE.md ne liste que le code et la doc du repo.
    all_files = [
        f for f in all_files if f != "docs/TREE.md" and not f.startswith(".vibe/")
    ]

    lines = [
        "# TREE — cpm-store",
        "# Auto-generated by `tools/generate-filemap.py` — do not edit by hand.",
        "# To read a file's full header: read the file itself (first ~20 lines).",
        "",
    ]
    for title, glob, marker in SECTIONS:
        files = sorted(f for f in all_files if pathlib.PurePath(f).match(glob))
        if not files:
            continue
        tree = build_tree(files)
        for f in files:
            pass
        # descriptions
        def annotate(node, prefix=""):
            for k, v in list(node.items()):
                if isinstance(v, dict):
                    annotate(v, prefix + k + "/")
                else:
                    node[k] = first_doc_line(ROOT / prefix / k, marker)
        annotate(tree)
        width = max((len(pathlib.PurePath(f).name) for f in files), default=0)
        lines.append(f"# ── {title} ──")
        lines.append("")
        render(tree, "", lines, width)
        lines.append("")

    stamp = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    lines.insert(3, f"# Generated {stamp}")
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"TREE régénéré : {OUT} ({len(all_files)} fichiers)")


if __name__ == "__main__":
    main()
